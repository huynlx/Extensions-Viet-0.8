    async getSearchResults(query, metadata) {
      const baseUrl = await this.getBaseUrl();
      const page = metadata?.page ?? 1;
      const search = {
        genres: "",
        exgenres: "",
        country: "0",
        status: "-1",
        minchapter: "0",
        sort: "0"
      };
      let rankingPath;
      const extags = query.excludedTags?.map((tag) => tag.id) ?? [];
      const exgenres = [];
      for (const value of extags) {
        if (value.indexOf(".") === -1) {
          exgenres.push(value);
        }
      }
      const tags = query.includedTags?.map((tag) => tag.id) ?? [];
      const genres = [];
      for (const value of tags) {
        if (value.indexOf(".") === -1) {
          genres.push(value);
        } else {
          const [key, val] = value.split(".");
          switch (key) {
            case "ranking":
              rankingPath = val;
              break;
            case "minchapter":
              search.minchapter = String(val);
              break;
            case "country":
              search.country = String(val);
              break;
            case "sort":
              search.sort = String(val);
              break;
            case "status":
              search.status = String(val);
              break;
          }
        }
      }
      search.genres = genres.join(",");
      search.exgenres = exgenres.join(",");
      let url = "";
      let param = "";
      if (rankingPath) {
        url = `${baseUrl}/${rankingPath}/trang-${page}`;
      } else {
        const paramExgenres = search.exgenres ? `&notcategory=${search.exgenres}` : "";
        url = `${baseUrl}/${query.title ? "tim-kiem" : "tim-kiem-nang-cao"}/trang-${page}`;
        param = `?q=${encodeURIComponent(query.title ?? "")}&category=${search.genres}${paramExgenres}&country=${search.country}&status=${search.status}&minchapter=${search.minchapter}&sort=${search.sort}`;
      }
      const fullUrl = url + param;
      const cacheKey = `search-${fullUrl}`;
      const now = Date.now();
      const cached = this.cache.get(cacheKey);
      let $;
      if (cached && now - cached.timestamp < this.CACHE_TTL) {
        $ = cached.data;
      } else {
        $ = await this.DOMHTML(fullUrl);
        this.cache.set(cacheKey, { data: $, timestamp: now });
      }
      const tiles = this.parser.parseSearchResults($);
      metadata = !isLastPage($) ? { page: page + 1 } : void 0;
      return App.createPagedResults({
        results: tiles,
        metadata
      });
    }
    async getViewMoreItems(homepageSectionId, metadata) {
      const baseUrl = await this.getBaseUrl();
      const page = metadata?.page ?? 1;
      let param = "";
      let url = "";
      switch (homepageSectionId) {
        case "favorite":
          param = `trang-${page}`;
          url = `${baseUrl}/truyen-yeu-thich/`;
          break;
        case "new_updated":
          param = `trang-${page}`;
          url = `${baseUrl}/truyen-moi-cap-nhat/`;
          break;
        case "new_added":
          param = `trang-${page}`;
          url = `${baseUrl}/truyen-tranh-moi/`;
          break;
        case "full":
          param = `trang-${page}?status=2`;
          url = `${baseUrl}/truyen-hoan-thanh/`;
          break;
        default:
          throw new Error("Requested to getViewMoreItems for a section ID which doesn't exist");
      }
      const cacheKey = `view-more-${url}-${param}`;
      const now = Date.now();
      const cached = this.cache.get(cacheKey);
      let $;
      if (cached && now - cached.timestamp < this.CACHE_TTL) {
        $ = cached.data;
      } else {
        const request = App.createRequest({
          url,
          method: "GET",
          param
        });
        const response = await this.requestManager.schedule(request, 1);
        $ = this.cheerio.load(response.data);
        this.cache.set(cacheKey, { data: $, timestamp: now });
      }
      const manga = this.parser.parseSearchResults($);
      metadata = isLastPage($) ? void 0 : { page: page + 1 };
      return App.createPagedResults({
        results: manga,
        metadata
      });
    }
